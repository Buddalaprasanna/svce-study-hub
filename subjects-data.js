/* Single source of truth for turning (dept, subject) into the key used
   to store/fetch files on the backend. Used by BOTH subject.js and
   upload.js so a file uploaded under "Physics (CSE)" always lands in
   the same bucket that subject.html looks it up from.
   Prevents "Physics (CSE)" and "Physics (ECE)" files from mixing. */
function makeSubjectKey(dept, subject) {
  return `${dept}_${subject}`.replace(/\s+/g, "-");
}

/* Flattens notesData and labsData into a list for the Upload page dropdown:
   [{ label: "Physics (CSE - P-Cycle)", subject: "Physics", dept: "CSE" }, ...] */
function getFlattenedSubjects() {
  const list = [];

  // Add theory subjects
  for (const level in notesData) {
    for (const dept in notesData[level]) {
      notesData[level][dept].forEach((sub) => {
        list.push({
          label: `${sub} (${dept} - ${level})`,
          subject: sub,
          dept: dept,
        });
      });
    }
  }
  
  // Add lab subjects
  for (const level in labsData) {
    for (const dept in labsData[level]) {
      labsData[level][dept].forEach((sub) => {
        list.push({
          label: `${sub} (${dept} - ${level} LAB)`,
          subject: sub,
          dept: dept,
        });
      });
    }
  }
  
  return list;
}

